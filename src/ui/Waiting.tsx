// 点开才去取的东西还没到的时候，站在它位置上的一句话：正在取是“加载中…”；没取到是另一句，告诉读者怎么再试。
// 再试有两步：关上再点开是再取一次（网断了一下的时候管用）；网站发了新的一版以后，旧的那一段程序已经不在了，
// 再取多少次也取不到，要刷新网页才行，所以后半句说的是刷新。
// role="status"：这一句是后来换进去的，读屏软件要念出来（不然没取到的时候，看不见屏幕的读者什么也听不到）。

export function Waiting({ failed }: { failed: boolean }) {
  return (
    <p className="quiet" role="status">
      {failed ? '没能读出来。关上再点开，可以再试一次；还不行，就刷新一下网页。' : '加载中…'}
    </p>
  );
}
